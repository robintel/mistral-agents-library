# Install the agent library as Mistral Vibe profiles - the Windows
# companion to install.py, for machines without Python. Same
# manifest, same composition, same defaults: the orchestrator as a
# selectable profile, the specialists as subagents, in
# ~\.vibe\agents. Reruns are idempotent; stale generated profiles
# are pruned. The generated header matches install.py's so the two
# installers recognize and prune each other's output. Byte-for-byte
# equivalence with install.py is a release test.
#
# Usage:
#   .\install.ps1                        install to ~\.vibe\agents
#   .\install.ps1 -Dest DIR             install elsewhere
#   .\install.ps1 -Target REPO          also write a thin AGENTS.md into REPO
#   .\install.ps1 -DryRun               print the plan, write nothing
#   install.bat                          same, from cmd
#   powershell -ExecutionPolicy Bypass -File .\install.ps1
#                                       (if running scripts is disabled)
#
# Kept ASCII-only on purpose: Windows PowerShell 5.1 reads a
# no-BOM script as ANSI, and any non-ASCII byte would corrupt.

param(
    [string]$Dest = [System.IO.Path]::Combine(
        [Environment]::GetFolderPath("UserProfile"), ".vibe", "agents"),
    [string]$Target,
    [switch]$DryRun
)

$ErrorActionPreference = "Stop"
$Repo = $PSScriptRoot
$ManifestPath = [System.IO.Path]::Combine($Repo, "manifest.yaml")
$StandardsPath = [System.IO.Path]::Combine($Repo, "shared", "standards.md")
$Header = "# Generated by install.py from manifest.yaml - regenerate, do not edit."
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)

# Tool surfaces, mirroring DEPLOYING.md and install.py: auditors,
# reviewers, and cartographers read-only; executors write-capable;
# reproducers with command access but no writes.
$ReadTools = @("grep", "read_file", "skill")
$RunTools = $ReadTools + @("bash")
$WriteTools = $ReadTools + @("bash", "write_file", "edit_file")
$WriteAgents = @(
    "implementer", "code-developer", "scaffolder", "test-engineer",
    "test-automator", "unit-test-writer", "devops",
    "dependency-upgrader", "migration-engineer",
    "data-migration-engineer", "rollback-operator", "secret-cleaner"
)
$RunAgents = @("debugger", "coverage-manager", "flaky-test-analyst")
$Acronyms = @{ gdpr = "GDPR"; qastell = "QAstell"; api = "API" }

function Read-Text([string]$Path) {
    # CRLF checkouts (core.autocrlf on Windows) must not leak \r
    # into profiles; everything the installer reads is LF.
    [System.IO.File]::ReadAllText($Path, [System.Text.Encoding]::UTF8).
        Replace("`r`n", "`n")
}

function Parse-Manifest([string]$Text) {
    $resolved = @{}
    $agents = New-Object System.Collections.Generic.List[hashtable]
    $routing = [ordered]@{}

    $block = [regex]::Match($Text, "(?ms)^  resolved:(.*?)^agents:")
    if (-not $block.Success) {
        throw "install.ps1: manifest.yaml: models.resolved block not found"
    }
    foreach ($m in [regex]::Matches($block.Groups[1].Value, "(?m)^\s*t(\d):\s*\[(.*)\]")) {
        $resolved["t" + $m.Groups[1].Value] = @(
            $m.Groups[2].Value.Split(",") |
                ForEach-Object { $_.Trim() } |
                Where-Object { $_ -ne "" }
        )
    }

    $block = [regex]::Match($Text, "(?ms)^agents:(.*?)^routing:")
    if (-not $block.Success) {
        throw "install.ps1: manifest.yaml: agents block not found"
    }
    foreach ($entry in [regex]::Matches($block.Groups[1].Value, "(?m)^\s*-\s*\{(.*)\}")) {
        $agent = @{}
        foreach ($field in [regex]::Matches($entry.Groups[1].Value, "(\w+):\s*(\[[^\]]*\]|[^,}]+)")) {
            $key = $field.Groups[1].Value
            $value = $field.Groups[2].Value.Trim()
            if ($value.StartsWith("[")) {
                $value = @(
                    $value.Substring(1, $value.Length - 2).Split(",") |
                        ForEach-Object { $_.Trim() } |
                        Where-Object { $_ -ne "" }
                )
            }
            $agent[$key] = $value
        }
        foreach ($key in @("name", "path", "domain", "tier")) {
            if (-not $agent.ContainsKey($key)) {
                throw ("install.ps1: manifest.yaml: agent missing '$key': " +
                       $entry.Value.Trim())
            }
        }
        $agents.Add($agent)
    }

    $block = [regex]::Match($Text, "(?ms)^routing:(.*?)^profiles:")
    if (-not $block.Success) {
        throw "install.ps1: manifest.yaml: routing block not found"
    }
    foreach ($row in [regex]::Matches($block.Groups[1].Value, "(?m)^  (\S+): (\S+)$")) {
        $routing[$row.Groups[1].Value] = $row.Groups[2].Value
    }

    [PSCustomObject]@{ Resolved = $resolved; Agents = $agents; Routing = $routing }
}

function Get-Tagline([string]$Body, [string]$Name) {
    # The first sentence after the H1 is the agent's description.
    $text = [regex]::Replace($Body, "(?s)^---\n.*?\n---\n", "")
    $lines = $text.Split("`n")
    for ($i = 0; $i -lt $lines.Count; $i++) {
        if ($lines[$i].StartsWith("# ")) {
            $paragraph = New-Object System.Collections.Generic.List[string]
            $started = $false
            for ($j = $i + 1; $j -lt $lines.Count; $j++) {
                if ([string]::IsNullOrWhiteSpace($lines[$j])) {
                    if ($started) { break } else { continue }
                }
                $started = $true
                $paragraph.Add($lines[$j].Trim())
            }
            $sentence = ([regex]::Split(($paragraph -join " "), "\. "))[0].Trim()
            $sentence = $sentence.Trim("*")
            if (-not $sentence.EndsWith(".")) { $sentence = $sentence + "." }
            return $sentence
        }
    }
    throw "install.ps1: ${Name}: no H1 heading found"
}

function Get-DisplayName([string]$Name) {
    $parts = foreach ($word in $Name.Split("-")) {
        if ($Acronyms.ContainsKey($word)) { $Acronyms[$word] }
        else { $word.Substring(0, 1).ToUpper() + $word.Substring(1) }
    }
    $parts -join " "
}

function ConvertTo-TomlString([string]$Value) {
    '"' + $Value.Replace('\', '\\').Replace('"', '\"') + '"'
}

function ConvertTo-TomlArray($Values) {
    "[" + (($Values | ForEach-Object { ConvertTo-TomlString $_ }) -join ", ") + "]"
}

function ConvertTo-TomlMultiline([string]$Content) {
    # LF-normalize before anything else: a CRLF checkout of this
    # very script leaks \r into its here-strings, and Python
    # normalizes install.py's source - byte-parity needs the same
    # here. Backslashes are escapes in TOML basic strings, and a
    # Windows library path is full of them. install.py validates
    # every profile by parsing it back; this port is proven by the
    # equivalence test against install.py's output.
    $c = $Content.Replace("`r`n", "`n").Replace('\', '\\')
    if (-not $c.EndsWith("`n")) { $c = $c + "`n" }
    'instructions = """' + "`n" + $c + '"""' + "`n"
}

function Get-Toolset([string]$Name) {
    if ($WriteAgents -contains $Name) { return ,@($WriteTools, "neutral", "write-capable") }
    if ($RunAgents -contains $Name) { return ,@($RunTools, "neutral", "command-armed") }
    return ,@($ReadTools, "safe", "read-only")
}

function Get-Addendum([string]$Name, [string]$Surface, [string]$Library) {
    if ($Name -eq "orchestrator") {
        return (@'
## Deployment addendum (Vibe)

You run as a selectable agent profile; your specialists are
subagent profiles, spawned by name. Every specialist in the routing
table below is deployed as a subagent. A name not in the table:
handle it yourself per your failure-handling rules, and say so.

The agent library lives at
{library} -
manifest.yaml is the routing registry; shared/dialects/ carries
the contracts your briefs reference by path.

Routing (task class -> agent):
'@).Replace("{library}", $Library)
    }
    return (@'
## Deployment addendum (Vibe)

You are a {surface} subagent; your enabled_tools are your surface,
nothing more. The library lives at
{library}.
manifest.yaml is the routing registry; shared/dialects/ carries
the contracts your briefs reference by path.
'@).Replace("{surface}", $Surface).Replace("{library}", $Library)
}

$parsed = Parse-Manifest (Read-Text $ManifestPath)
$agents = $parsed.Agents
$resolved = $parsed.Resolved
$routing = $parsed.Routing

if ($agents.Count -lt 2) {
    throw ("install.ps1: manifest.yaml: expected the orchestrator plus " +
           "specialists, found $($agents.Count) agents")
}
if ($routing.Count -eq 0) {
    throw "install.ps1: manifest.yaml: no routing rows parsed"
}
foreach ($agent in $agents) {
    $tier = $agent["tier"]
    if (-not $resolved.ContainsKey($tier) -or $resolved[$tier].Count -eq 0) {
        throw ("install.ps1: $($agent['name']): tier $tier has no models in " +
               "models.resolved - the catalog is data with an owner; " +
               "refresh it in manifest.yaml first")
    }
    # The strongest model of the tier: the resolved lists run
    # cheapest-first, so the last entry is the tier's ceiling.
    $agent["model"] = $resolved[$tier][-1]
}

$standards = (Read-Text $StandardsPath).TrimEnd()
$profiles = New-Object System.Collections.Generic.List[object]
foreach ($agent in $agents) {
    $name = $agent["name"]
    $bodyPath = [System.IO.Path]::Combine($Repo, ($agent["path"] -replace "/", [System.IO.Path]::DirectorySeparatorChar))
    if (-not [System.IO.File]::Exists($bodyPath)) {
        throw "install.ps1: ${name}: body not found at $($agent['path'])"
    }
    $body = (Read-Text $bodyPath).Trim()
    $tagline = Get-Tagline $body $name

    $toolset = Get-Toolset $name
    $addendumText = Get-Addendum $name $toolset[2] $Repo
    $instructions = $standards + "`n`n---`n`n" + $body + "`n`n" +
        $addendumText + "`n"
    if ($name -eq "orchestrator") {
        $rows = foreach ($cls in $routing.Keys) { "- $cls -> $($routing[$cls])" }
        $instructions = $instructions + ($rows -join "`n") + "`n"
        $text = $Header + "`n" +
            "display_name = " + (ConvertTo-TomlString (Get-DisplayName $name + " (Mistral Agents Library)")) + "`n" +
            "description = " + (ConvertTo-TomlString $tagline) + "`n" +
            'safety = "neutral"' + "`n" +
            "active_model = " + (ConvertTo-TomlString $agent["model"]) + "`n`n" +
            (ConvertTo-TomlMultiline $instructions)
    } else {
        $text = $Header + "`n" +
            "display_name = " + (ConvertTo-TomlString (Get-DisplayName $name + " (Mistral Agents Library)")) + "`n" +
            "description = " + (ConvertTo-TomlString $tagline) + "`n" +
            "safety = " + (ConvertTo-TomlString $toolset[1]) + "`n" +
            'agent_type = "subagent"' + "`n" +
            "enabled_tools = " + (ConvertTo-TomlArray $toolset[0]) + "`n" +
            "active_model = " + (ConvertTo-TomlString $agent["model"]) + "`n`n" +
            (ConvertTo-TomlMultiline $instructions)
    }
    $profiles.Add([PSCustomObject]@{ Name = $name; Text = $text })
}

$stale = @()
if ([System.IO.Directory]::Exists($Dest)) {
    $current = @{}
    foreach ($p in $profiles) { $current[$p.Name + ".toml"] = $true }
    foreach ($file in [System.IO.Directory]::GetFiles($Dest, "*.toml")) {
        $fileName = [System.IO.Path]::GetFileName($file)
        if ($current.ContainsKey($fileName)) { continue }
        $first = (([System.IO.File]::ReadAllText($file, [System.Text.Encoding]::UTF8)) -split "`n")[0]
        if ($first.Trim() -eq $Header) { $stale += $fileName }
    }
}

$verb = "Installing"
if ($DryRun) { $verb = "Would install" }
Write-Host "$verb $($profiles.Count) profiles -> $Dest"
foreach ($p in $profiles) { Write-Host "  $($p.Name).toml" }
$pruneVerb = "Pruning"
if ($DryRun) { $pruneVerb = "Would prune" }
if ($stale.Count -gt 0) {
    Write-Host "$pruneVerb (stale, not in manifest):"
    foreach ($name in ($stale | Sort-Object)) { Write-Host "  $name" }
}

# Skills: ship every directory that contains a SKILL.md to
# ~/.vibe/skills (or the corresponding sibling of -Dest).
$skillsDest = [System.IO.Path]::Combine(
    [System.IO.Path]::GetDirectoryName($Dest), "skills")
$skillsInstalled = @()
$skillsSrc = [System.IO.Path]::Combine($Repo, "skills")
if ([System.IO.Directory]::Exists($skillsSrc)) {
    foreach ($skillDir in [System.IO.Directory]::GetDirectories($skillsSrc)) {
        $skillMd = [System.IO.Path]::Combine($skillDir, "SKILL.md")
        if (-not [System.IO.File]::Exists($skillMd)) { continue }
        $skillsInstalled += [System.IO.Path]::GetFileName($skillDir)
    }
    $verb = "Would install"
    if (-not $DryRun) { $verb = "Installed" }
    Write-Host "$verb $($skillsInstalled.Count) skills -> $skillsDest"
}

if ($DryRun) { return }

if (-not [System.IO.Directory]::Exists($Dest)) {
    [System.IO.Directory]::CreateDirectory($Dest) | Out-Null
}
foreach ($p in $profiles) {
    [System.IO.File]::WriteAllText(
        [System.IO.Path]::Combine($Dest, $p.Name + ".toml"),
        $p.Text, $Utf8NoBom)
}
foreach ($name in $stale) {
    [System.IO.File]::Delete([System.IO.Path]::Combine($Dest, $name))
}

# Copy skills for real
if ($skillsInstalled.Count -gt 0) {
    foreach ($skillDir in [System.IO.Directory]::GetDirectories($skillsSrc)) {
        $skillMd = [System.IO.Path]::Combine($skillDir, "SKILL.md")
        if (-not [System.IO.File]::Exists($skillMd)) { continue }
        $targetSkillDir = [System.IO.Path]::Combine(
            $skillsDest, [System.IO.Path]::GetFileName($skillDir))
        if ([System.IO.Directory]::Exists($targetSkillDir)) {
            [System.IO.Directory]::Delete($targetSkillDir, $true)
        }
        [System.IO.Directory]::CreateDirectory($targetSkillDir) | Out-Null
        foreach ($file in [System.IO.Directory]::GetFiles($skillDir)) {
            $targetFile = [System.IO.Path]::Combine(
                $targetSkillDir, [System.IO.Path]::GetFileName($file))
            [System.IO.File]::Copy($file.FullName, $targetFile)
        }
    }
}

if ($Target -ne "") {
    if (-not [System.IO.Directory]::Exists($Target)) {
        throw "install.ps1: -Target: not a directory: $Target"
    }
    $agentsMd = [System.IO.Path]::Combine($Target, "AGENTS.md")
    if ([System.IO.File]::Exists($agentsMd)) {
        throw "install.ps1: -Target: $agentsMd already exists; not overwriting it"
    }
    [System.IO.File]::WriteAllText($agentsMd, (@'
# Agent library

Run the `orchestrator` agent profile (Shift+Tab, or
`vibe --agent orchestrator`). The agent library lives at
{library}: manifest.yaml is the routing registry,
shared/standards.md the shared contract, shared/dialects/
the language floors. Specialists arrive as briefs from the
orchestrator, never as direct commands.
'@).Replace("`r`n", "`n").Replace("{library}", $Repo) + "`n", $Utf8NoBom)
    Write-Host "Wrote $agentsMd"
}

Write-Host "Done. Reload the VS Code window (or restart the CLI), then"
Write-Host "run: vibe --agent orchestrator"
