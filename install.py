#!/usr/bin/env python3
"""Install the agent library as Mistral Vibe profiles.

Reads manifest.yaml — the single source of truth — and composes every
agent into a self-contained TOML profile: shared/standards.md plus the
agent body, the tier's model from models.resolved, and the role's tool
surface (the sets live below; DEPLOYING.md documents the mapping).

The orchestrator lands as a selectable profile; every other agent
lands as a subagent the orchestrator spawns by name. Files from
earlier installs that carry the generated header and no longer exist
in the manifest are pruned. Idempotent: rerunning reproduces the same
files. Exit codes: 0 installed, 1 anything failed.

Usage:
  ./install.py                    install to ~/.vibe/agents
  ./install.py --dest DIR         install elsewhere
  ./install.py --target REPO      also write a thin AGENTS.md into REPO
  ./install.py --dry-run          print the plan, write nothing
  ./install.py --check            check if updates are available
  ./install.py --update           pull latest changes and reinstall
"""

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent
MANIFEST = REPO / "manifest.yaml"
STANDARDS = REPO / "shared" / "standards.md"
SKILLS_DIR = REPO / "skills"
HEADER = "# Generated by install.py from manifest.yaml - regenerate, do not edit."

# Tool surfaces, mirroring DEPLOYING.md: auditors, reviewers, and
# cartographers read-only (the Explore trio); executors write-capable;
# reproducers with command access but no writes.
READ_TOOLS = ["grep", "read_file", "skill"]
RUN_TOOLS = READ_TOOLS + ["bash"]
WRITE_TOOLS = READ_TOOLS + ["bash", "write_file", "edit_file"]
WRITE_AGENTS = {
    "implementer", "code-developer", "scaffolder", "test-engineer",
    "test-automator", "unit-test-writer", "devops",
    "dependency-upgrader", "migration-engineer",
    "data-migration-engineer", "rollback-operator", "secret-cleaner",
}
RUN_AGENTS = {"debugger", "coverage-manager", "flaky-test-analyst"}

ACRONYMS = {"gdpr": "GDPR", "qastell": "QAstell", "api": "API"}


def fail(message):
    sys.exit(f"install.py: {message}")


def read_text(path):
    """CRLF checkouts (core.autocrlf on Windows) must not leak \r into
    profiles; everything the installer reads is normalized to LF."""
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def read_skills():
    """Read every SKILL.md frontmatter: (name, description) per skill.
    Used to compose the orchestrator's skills addendum so it can
    suggest the right slash command when a user's request matches."""
    skills = []
    if not SKILLS_DIR.is_dir():
        return skills
    for skill_dir in sorted(SKILLS_DIR.iterdir()):
        if not skill_dir.is_dir():
            continue
        skill_md = skill_dir / "SKILL.md"
        if not skill_md.is_file():
            continue
        text = read_text(skill_md)
        fm = re.search(r"^---\n(.*?)\n---", text, re.S)
        if not fm:
            continue
        name_m = re.search(r"^name:\s*(.+)$", fm.group(1), re.M)
        desc_m = re.search(r'^description:\s*["\']?(.+?)["\']?\s*$', fm.group(1), re.M)
        if name_m:
            skills.append((name_m.group(1).strip(),
                           desc_m.group(1).strip() if desc_m else ""))
    return skills


def parse_manifest(text):
    """Parse the blocks the installer needs: models.resolved, agents,
    routing. Targeted on purpose: the manifest is hand-maintained and
    regular; a general YAML parser would add a dependency for this."""
    resolved, agents, routing = {}, [], {}

    block = re.search(r"^  resolved:(.*?)^agents:", text, re.S | re.M)
    if not block:
        fail("manifest.yaml: models.resolved block not found")
    for line in block.group(1).splitlines():
        tier = re.match(r"\s*t(\d):\s*\[(.*)\]", line)
        if tier:
            resolved[f"t{tier.group(1)}"] = [
                m.strip() for m in tier.group(2).split(",") if m.strip()
            ]

    block = re.search(r"^agents:(.*?)^routing:", text, re.S | re.M)
    if not block:
        fail("manifest.yaml: agents block not found")
    for line in block.group(1).splitlines():
        entry = re.match(r"\s*-\s*{(.*)}", line)
        if not entry:
            continue
        agent = {}
        for key, value in re.findall(r"(\w+):\s*(\[[^\]]*\]|[^,}]+)",
                                     entry.group(1)):
            value = value.strip()
            if value.startswith("["):
                value = [v.strip() for v in value[1:-1].split(",") if v.strip()]
            agent[key] = value
        for key in ("name", "path", "domain", "tier"):
            if key not in agent:
                fail(f"manifest.yaml: agent missing '{key}': {line.strip()}")
        agents.append(agent)

    block = re.search(r"^routing:(.*?)^profiles:", text, re.S | re.M)
    if not block:
        fail("manifest.yaml: routing block not found")
    for line in block.group(1).splitlines():
        row = re.match(r"^  (\S+): (\S+)$", line)
        if row:
            routing[row.group(1)] = row.group(2)

    return resolved, agents, routing


def extract_tagline(body, name):
    """The first sentence after the H1 is the agent's description."""
    text = re.sub(r"^---\n.*?\n---\n", "", body, flags=re.S)
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("# "):
            paragraph, started = [], False
            for candidate in lines[i + 1:]:
                if not candidate.strip():
                    if started:
                        break
                    continue
                started = True
                paragraph.append(candidate.strip())
            sentence = " ".join(paragraph).split(". ")[0].strip()
            sentence = sentence.strip("*")
            return sentence + ("" if sentence.endswith(".") else ".")
    fail(f"{name}: no H1 heading found")


def display_name(name):
    words = []
    for word in name.split("-"):
        words.append(ACRONYMS.get(word, word.capitalize()))
    return " ".join(words)


def toml_multiline(content):
    # Use TOML literal strings (single-quoted) to avoid conflicts with
    # Python docstrings and other content that may contain triple double-quotes.
    # Literal strings don't interpret escape sequences, so backslashes don't
    # need escaping, and triple double-quotes in the content are safe.
    if not content.endswith("\n"):
        content += "\n"
    return f'instructions = \'\'\'\n{content}\'\'\'\n'


def toml_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def toml_array(values):
    return "[" + ", ".join(toml_string(v) for v in values) + "]"


def toolset_for(name):
    if name in WRITE_AGENTS:
        return WRITE_TOOLS, "neutral", "write-capable"
    if name in RUN_AGENTS:
        return RUN_TOOLS, "neutral", "command-armed"
    return READ_TOOLS, "safe", "read-only"


def addendum(name, surface, library):
    if name == "orchestrator":
        return f"""## Deployment addendum (Vibe)

You run as a selectable agent profile; your specialists are
subagent profiles, spawned by name. Every specialist in the routing
table below is deployed as a subagent. A name not in the table:
handle it yourself per your failure-handling rules, and say so.

The agent library lives at
{library} -
manifest.yaml is the routing registry; shared/dialects/ carries
the contracts your briefs reference by path.

Routing (task class -> agent):"""
    return f"""## Deployment addendum (Vibe)

You are a {surface} subagent; your enabled_tools are your surface,
nothing more. The library lives at
{library}.
manifest.yaml is the routing registry; shared/dialects/ carries
the contracts your briefs reference by path."""


def compose(agents, routing, library, skills=None):
    """One (name, TOML text, instructions) per agent, in manifest order."""
    profiles = []
    standards = read_text(STANDARDS).rstrip()
    for agent in agents:
        name = agent["name"]
        body_path = REPO / agent["path"]
        if not body_path.is_file():
            fail(f"{name}: body not found at {agent['path']}")
        body = read_text(body_path).strip()

        instructions = (
            standards + "\n\n---\n\n" + body + "\n\n"
            + addendum(name, toolset_for(name)[2], library) + "\n"
        )
        if name == "orchestrator":
            instructions += "\n".join(
                f"- {cls} -> {target}" for cls, target in routing.items()
            ) + "\n"
            if skills:
                instructions += (
                    "\n## Available skills (slash commands)\n\n"
                    "These are user-invocable workflow skills installed\n"
                    "alongside the agents. When the user's request matches\n"
                    "a skill's purpose, suggest invoking it as a slash\n"
                    "command — do not attempt the skill's work yourself.\n"
                    "The user invokes the skill; it runs as its own agent.\n\n"
                    + "\n".join(
                        f"- /{s[0]}: {s[1]}" for s in skills
                    ) + "\n"
                )
            text = (
                f"{HEADER}\n"
                f"display_name = {toml_string(display_name(name) + ' (Mistral Agents Library)')}\n"
                f"description = {toml_string(extract_tagline(body, name))}\n"
                f'safety = "neutral"\n'
                f"active_model = {toml_string(agent['model'])}\n\n"
                + toml_multiline(instructions)
            )
        else:
            tools, safety, _ = toolset_for(name)
            text = (
                f"{HEADER}\n"
                f"display_name = {toml_string(display_name(name) + ' (Mistral Agents Library)')}\n"
                f"description = {toml_string(extract_tagline(body, name))}\n"
                f"safety = {toml_string(safety)}\n"
                f'agent_type = "subagent"\n'
                f"enabled_tools = {toml_array(tools)}\n"
                f"active_model = {toml_string(agent['model'])}\n\n"
                + toml_multiline(instructions)
            )
        profiles.append((name, text, instructions))
    return profiles


def validate(name, text, instructions):
    """A generated profile must parse, and the round-tripped instructions
    must equal the composed content — a batch that silently mangles a
    body would otherwise ship unverified."""
    try:
        import tomllib
    except ImportError:
        return
    try:
        parsed = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        fail(f"{name}: generated TOML does not parse: {error}")
    if parsed.get("instructions") != instructions:
        fail(f"{name}: instructions corrupted in TOML escaping")


def get_manifest_version():
    """Read the version from manifest.yaml."""
    text = read_text(MANIFEST)
    match = re.search(r'^version:\s*(\S+)', text, re.MULTILINE)
    if match:
        return match.group(1)
    return "unknown"


def get_installed_version(dest):
    """Read the installed version from the version marker file."""
    version_file = dest / ".mal_version"
    if version_file.is_file():
        return version_file.read_text(encoding="utf-8").strip()
    # Fallback: check if any generated profiles exist
    for existing in dest.glob("*.toml"):
        first = existing.read_text(encoding="utf-8").splitlines()[:1]
        if first and first[0].strip() == HEADER:
            # Version is embedded in the HEADER comment
            # For now, return "installed" to indicate something is there
            return "installed"
    return None


def get_remote_version():
    """Get the latest version from the remote repository."""
    try:
        result = subprocess.run(
            ["git", "ls-remote", "origin", "HEAD"],
            cwd=REPO,
            capture_output=True,
            text=True,
            check=True
        )
        # Extract commit hash (first field of first line)
        remote_commit = result.stdout.split()[0] if result.stdout else None
        if remote_commit:
            # Get the manifest version from the remote commit
            result = subprocess.run(
                ["git", "show", f"{remote_commit}:manifest.yaml"],
                cwd=REPO,
                capture_output=True,
                text=True,
                check=True
            )
            text = result.stdout.replace("\r\n", "\n")
            match = re.search(r'^version:\s*(\S+)', text, re.MULTILINE)
            if match:
                return match.group(1)
        # If we can't parse the version, return the commit hash as a fallback
        return remote_commit[:8] if remote_commit else "unknown"
    except (subprocess.CalledProcessError, FileNotFoundError, IndexError):
        return "unknown"


def show_changelog(current, latest):
    """Show the changelog entries between current and latest versions."""
    try:
        changelog = REPO / "CHANGELOG.md"
        if not changelog.is_file():
            return
        text = read_text(changelog)
        # Extract version sections
        sections = re.findall(
            r'## \[([^\]]+)\]\s*([\s\S]*?)(?=## \[|\Z)',
            text
        )
        found_current = False
        for version, content in sections:
            if version == current:
                found_current = True
                continue
            if found_current:
                if version == latest:
                    print(f"\nChangelog since v{current}:")
                    print(content.strip())
                    break
                # If we haven't found latest yet, keep looking
    except Exception:
        pass  # Silently skip if we can't show changelog


def main():
    parser = argparse.ArgumentParser(
        description="Install the agent library as Mistral Vibe profiles.")
    parser.add_argument("--dest", type=Path,
                        default=Path.home() / ".vibe" / "agents",
                        help="profile directory (default: ~/.vibe/agents)")
    parser.add_argument("--target", type=Path,
                        help="also write a thin AGENTS.md into this repo")
    parser.add_argument("--dry-run", action="store_true",
                        help="print the plan, write nothing")
    parser.add_argument("--check", action="store_true",
                        help="check if updates are available (no changes)")
    parser.add_argument("--update", action="store_true",
                        help="pull latest changes from origin and reinstall")
    args = parser.parse_args()

    if not MANIFEST.is_file():
        fail(f"manifest.yaml not found next to the script: {MANIFEST}")
    if not STANDARDS.is_file():
        fail(f"shared/standards.md not found: {STANDARDS}")

    # Handle --check and --update
    if args.check or args.update:
        current_version = get_installed_version(args.dest)
        latest_version = get_remote_version()
        manifest_version = get_manifest_version()

        if current_version is None:
            print(f"No installation found in {args.dest}")
            if args.check:
                return
        elif current_version == latest_version or current_version == manifest_version:
            print(f"Already up to date (v{current_version})")
            if args.check:
                return
        else:
            print(f"Update available: v{current_version} → v{manifest_version}")
            if args.check:
                show_changelog(current_version, manifest_version)
                return
            # --update will proceed to pull and install

        if args.update:
            print("Pulling latest changes...")
            try:
                subprocess.run(
                    ["git", "pull"],
                    cwd=REPO,
                    check=True,
                    capture_output=True,
                    text=True
                )
                print("Latest changes pulled successfully.")
            except subprocess.CalledProcessError as e:
                fail(f"Failed to pull changes: {e.stderr}")
            except FileNotFoundError:
                fail("git command not found. Please ensure git is installed.")

    resolved, agents, routing = parse_manifest(read_text(MANIFEST))
    if len(agents) < 2:
        fail(f"manifest.yaml: expected the orchestrator plus specialists, "
             f"found {len(agents)} agents")
    if not routing:
        fail("manifest.yaml: no routing rows parsed")

    for agent in agents:
        tier = agent["tier"]
        if tier not in resolved or not resolved[tier]:
            fail(f"{agent['name']}: tier {tier} has no models in "
                 f"models.resolved - the catalog is data with an owner; "
                 f"refresh it in manifest.yaml first")
        # The strongest model of the tier: the resolved lists run
        # cheapest-first, so the last entry is the tier's ceiling.
        agent["model"] = resolved[tier][-1]

    profiles = compose(agents, routing, REPO, skills=read_skills())
    for name, text, instructions in profiles:
        validate(name, text, instructions)

    stale = []
    if args.dest.is_dir():
        current = {f"{name}.toml" for name, _, _ in profiles}
        for existing in args.dest.glob("*.toml"):
            if existing.name in current:
                continue
            first = existing.read_text(encoding="utf-8").splitlines()[:1]
            if first and first[0].strip() == HEADER:
                stale.append(existing.name)

    verb = "Would install" if args.dry_run else "Installing"
    print(f"{verb} {len(profiles)} profiles -> {args.dest}")
    for name, _, _ in profiles:
        print(f"  {name}.toml")
    if stale:
        print(f"{'Would prune' if args.dry_run else 'Pruning'} "
              f"(stale, not in manifest):")
        for name in sorted(stale):
            print(f"  {name}")

    # Skills: ship every directory that contains a SKILL.md to
    # ~/.vibe/skills (or the corresponding sibling of --dest).
    skills_dest = args.dest.parent / "skills"
    installed_skills = []
    if SKILLS_DIR.is_dir():
        for skill_dir in SKILLS_DIR.iterdir():
            if not skill_dir.is_dir():
                continue
            skill_md = skill_dir / "SKILL.md"
            if not skill_md.is_file():
                continue
            installed_skills.append(skill_dir.name)
    if installed_skills:
        verb = "Would install" if args.dry_run else "Installed"
        print(f"{verb} {len(installed_skills)} skills -> {skills_dest}")

    if args.dry_run:
        return

    args.dest.mkdir(parents=True, exist_ok=True)
    for name, text, _ in profiles:
        (args.dest / f"{name}.toml").write_text(text, encoding="utf-8")
    for name in stale:
        (args.dest / name).unlink()

    # Write version marker
    version_file = args.dest / ".mal_version"
    version_file.write_text(get_manifest_version(), encoding="utf-8")

    # Copy skills for real
    if installed_skills:
        for skill_dir in SKILLS_DIR.iterdir():
            if not skill_dir.is_dir():
                continue
            skill_md = skill_dir / "SKILL.md"
            if not skill_md.is_file():
                continue
            target_dir = skills_dest / skill_dir.name
            if target_dir.exists():
                shutil.rmtree(target_dir)
            shutil.copytree(skill_dir, target_dir)

    if args.target:
        target = args.target.resolve()
        if not target.is_dir():
            fail(f"--target: not a directory: {target}")
        agents_md = target / "AGENTS.md"
        if agents_md.exists():
            fail(f"--target: {agents_md} already exists; not overwriting it")
        agents_md.write_text(
            "# Agent library\n\n"
            "Run the `orchestrator` agent profile (Shift+Tab, or\n"
            "`vibe --agent orchestrator`). The agent library lives at\n"
            f"{REPO}: manifest.yaml is the routing registry,\n"
            "shared/standards.md the shared contract, shared/dialects/\n"
            "the language floors. Specialists arrive as briefs from the\n"
            "orchestrator, never as direct commands.\n",
            encoding="utf-8",
        )
        print(f"Wrote {agents_md}")

    print("Done. Reload the VS Code window (or restart the CLI), then\n"
          "run: vibe --agent orchestrator")


if __name__ == "__main__":
    main()
